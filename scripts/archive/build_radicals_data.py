print("1. Extracting full radical mapping from KANJIDIC2...")
rad_map = {}
with gzip.open('data/kanjidic2.xml.gz', 'rb') as f:
    tree = ET.parse(f)
    root = tree.getroot()
    for char in root.findall('character'):
        lit = char.find('literal')
        if lit is not None:
            kanji = lit.text
            rad_elem = char.find(".//rad_value[@rad_type='classical']")
            if rad_elem is not None:
                rad_map[kanji] = int(rad_elem.text)

print(f"Loaded {len(rad_map)} kanji classical radicals.")

# 2. Enrich and update data/kanji-levels/*.json
print("2. Enriching data/kanji-levels/*.json...")
level_files = glob.glob('data/kanji-levels/kanken-*.json')
all_updated_kanji = []

# Create number -> radical char lookup
num_to_char = {item[0]: item[1] for item in KANGXI_RADICALS_INFO}

for lpath in level_files:
    with open(lpath, 'r', encoding='utf-8') as fp:
        k_list = json.load(fp)
    
    for k in k_list:
        char = k.get('kanji')
        true_rad = rad_map.get(char, k.get('radical', 1))
        k['radical'] = true_rad
        k['radicalChar'] = num_to_char.get(true_rad, '一')
    
    with open(lpath, 'w', encoding='utf-8') as fp:
        json.dump(k_list, fp, ensure_ascii=False, indent=2)

# 3. Rebuild data/kanji.min.json
print("3. Rebuilding data/kanji.min.json...")
order = [
    'kanken-10.json', 'kanken-9.json', 'kanken-8.json', 'kanken-7.json',
    'kanken-6.json',  'kanken-5.json', 'kanken-4.json', 'kanken-3.json',
    'kanken-jun2.json', 'kanken-2.json', 'kanken-jun1.json', 'kanken-1.json'
]
combined = []
for ofile in order:
    p = os.path.join('data', 'kanji-levels', ofile)
    if os.path.exists(p):
        with open(p, 'r', encoding='utf-8') as fp:
            combined.extend(json.load(fp))

with open('data/kanji.min.json', 'w', encoding='utf-8') as fp:
    json.dump(combined, fp, ensure_ascii=False, separators=(',', ':'))
print(f"Rebuilt kanji.min.json with {len(combined)} kanji.")

# 4. Compute exact stats per radical
print("4. Calculating kanji counts per radical...")
rad_total_counts = {}
rad_joyo_counts = {}

for k in combined:
    r = k.get('radical')
    if r:
        rad_total_counts[r] = rad_total_counts.get(r, 0) + 1
        if k.get('joyo'):
            rad_joyo_counts[r] = rad_joyo_counts.get(r, 0) + 1

# 5. Build final data/radicals.json
print("5. Generating data/radicals.json...")
radicals_json_data = []

for item in KANGXI_RADICALS_INFO:
    num, char, variants, strokes, name_jp, position, meaning_th = item
    radicals_json_data.append({
        "number": num,
        "radical": char,
        "variants": variants,
        "strokes": strokes,
        "name_jp": name_jp,
        "position": position,
        "meaning_th": meaning_th,
        "total_kanji": rad_total_counts.get(num, 0),
        "joyo_count": rad_joyo_counts.get(num, 0)
    })

with open('data/radicals.json', 'w', encoding='utf-8') as fp:
    json.dump(radicals_json_data, fp, ensure_ascii=False, indent=2)

print(f"Successfully generated data/radicals.json with {len(radicals_json_data)} radicals!")
